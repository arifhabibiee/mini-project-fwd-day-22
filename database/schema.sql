-- PostgreSQL 17 foundation; matches PRD section 13.
-- Run once on a database without these tables. This is not a rerunnable migration.
-- Docker's entrypoint runs this file only when its data directory is empty.
-- No product data or application roles are created in this phase.

BEGIN;

CREATE TABLE public.products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL,
    name TEXT NOT NULL,
    subtitle TEXT NOT NULL,
    description TEXT NOT NULL,
    price_minor INTEGER NOT NULL,
    currency TEXT NOT NULL,
    min_quantity INTEGER NOT NULL DEFAULT 1,
    max_per_order INTEGER,
    content JSONB NOT NULL,

    CONSTRAINT products_id_positive CHECK (id > 0),
    CONSTRAINT products_slug_unique UNIQUE (slug),
    CONSTRAINT products_slug_nonblank CHECK (slug ~ '[^[:space:]]'),
    CONSTRAINT products_name_nonblank CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT products_subtitle_nonblank CHECK (subtitle ~ '[^[:space:]]'),
    CONSTRAINT products_description_nonblank CHECK (description ~ '[^[:space:]]'),
    CONSTRAINT products_price_minor_nonnegative CHECK (price_minor >= 0),
    CONSTRAINT products_currency_usd CHECK (currency = 'USD'),
    CONSTRAINT products_min_quantity_one CHECK (min_quantity = 1),
    CONSTRAINT products_max_per_order_valid
        CHECK (max_per_order IS NULL OR max_per_order >= min_quantity),
    CONSTRAINT products_content_object CHECK (jsonb_typeof(content) = 'object')
);

CREATE TABLE public.product_variants (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL,
    color_code TEXT NOT NULL,
    label TEXT NOT NULL,
    reference_variant_id TEXT,
    availability TEXT NOT NULL DEFAULT 'unknown',
    stock_quantity INTEGER,
    is_default BOOLEAN NOT NULL DEFAULT false,
    position INTEGER NOT NULL,

    CONSTRAINT product_variants_id_positive CHECK (id > 0),
    CONSTRAINT product_variants_product_fk FOREIGN KEY (product_id)
        REFERENCES public.products (id) ON DELETE CASCADE,
    CONSTRAINT product_variants_product_color_unique UNIQUE (product_id, color_code),
    CONSTRAINT product_variants_product_position_unique UNIQUE (product_id, position),
    CONSTRAINT product_variants_reference_id_unique UNIQUE (reference_variant_id),
    CONSTRAINT product_variants_color_code_nonblank CHECK (color_code ~ '[^[:space:]]'),
    CONSTRAINT product_variants_label_nonblank CHECK (label ~ '[^[:space:]]'),
    CONSTRAINT product_variants_reference_id_nonblank
        CHECK (reference_variant_id IS NULL OR reference_variant_id ~ '[^[:space:]]'),
    CONSTRAINT product_variants_availability_valid
        CHECK (availability IN ('available', 'unavailable', 'unknown')),
    CONSTRAINT product_variants_stock_nonnegative
        CHECK (stock_quantity IS NULL OR stock_quantity >= 0),
    CONSTRAINT product_variants_available_stock_valid
        CHECK (availability <> 'available' OR stock_quantity IS NULL OR stock_quantity > 0),
    CONSTRAINT product_variants_position_nonnegative CHECK (position >= 0)
);

-- At most one default per product. Seed/API validation must additionally ensure
-- exactly one default and at least one variant for each complete product.
CREATE UNIQUE INDEX product_variants_one_default_per_product
    ON public.product_variants (product_id)
    WHERE is_default;

CREATE TABLE public.product_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id INTEGER NOT NULL,
    url TEXT NOT NULL,
    alt TEXT NOT NULL,
    fallback_url TEXT,
    position INTEGER NOT NULL,

    CONSTRAINT product_images_id_positive CHECK (id > 0),
    CONSTRAINT product_images_variant_fk FOREIGN KEY (variant_id)
        REFERENCES public.product_variants (id) ON DELETE CASCADE,
    CONSTRAINT product_images_variant_position_unique UNIQUE (variant_id, position),
    CONSTRAINT product_images_url_nonblank CHECK (url ~ '[^[:space:]]'),
    CONSTRAINT product_images_alt_nonblank CHECK (alt ~ '[^[:space:]]'),
    CONSTRAINT product_images_fallback_url_nonblank
        CHECK (fallback_url IS NULL OR fallback_url ~ '[^[:space:]]'),
    CONSTRAINT product_images_position_nonnegative CHECK (position >= 0)
);

-- UNIQUE constraints above already index product_id/variant_id with position.
-- API/seed validation will check nested editorial content, URL safety, image
-- completeness and derived purchasable; no redundant purchasable column.
-- NULL stock_quantity means unknown stock, never zero or unlimited.
-- NULL max_per_order means no known business limit, not unlimited inventory.
-- Future seed inserts with explicit IDs must advance the identity sequences.

COMMIT;
